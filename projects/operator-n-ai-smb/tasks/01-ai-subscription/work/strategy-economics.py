"""Три условных сценария для O4. Входы E38, результат E39."""
from decimal import Decimal, ROUND_CEILING
from pathlib import Path

D = Decimal
F, K, H = D("100000"), D("300000"), D("12")
SCENARIOS = [
    ("Осторожный", "300", "300", "3000", "0.10", "200"),
    ("Базовый", "600", "100", "1000", "0.05", "500"),
    ("Смелый", "900", "100", "1000", "0.03", "1000"),
]


def threshold(numerator, denominator):
    return "нет" if denominator <= 0 else format((numerator / denominator).to_integral_value(rounding=ROUND_CEILING), ".0f")


def main():
    lines = [
        "# Три сценария партнёрского бизнеса",
        "",
        "Входы — гипотезы [E38], результаты — оценки [E39]. Не прогноз и не смета теста. "
        "Чистая комиссия уже после расчётов с поставщиком и косвенных налогов. "
        "n — число клиентов, N — оператор. Стабильная база предполагается с первого месяца; "
        "для реального запуска нужен помесячный расчёт роста и денежных разрывов.",
        "",
        "F = 100 000 ₽/мес., K = 300 000 ₽ подготовки без первоначального привлечения, H = 12 месяцев. "
        "C — комиссия/месяц, S — все переменные расходы N/месяц, A — полная продажа и подключение, h — месячный уход. "
        "g=C−S−hA; месячный результат=n*g−F. Начальные расходы K+n*A. "
        "Результат за H: H*(n*g−F)−K−n*A; порог H=ceil((H*F+K)/(H*g−A)). "
        "Все суммы в рублях, до налога на прибыль и финансирования, без задержек выплаты комиссии.",
        "",
        "| Сценарий | C | S | A | h | n | g/мес. | Результат/мес. | Операционный порог | Порог покрытия начальных расходов за 12 мес. | Срок покрытия при данном n, мес. |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, c, s, a, h, n in SCENARIOS:
        c, s, a, h, n = map(D, (c, s, a, h, n))
        g = c - s - h * a
        monthly = n * g - F
        recovery = "нет" if monthly <= 0 else f"{(K + n * a) / monthly:.2f}"
        lines.append(f"| {name} | {c:.0f} | {s:.0f} | {a:.0f} | {h:.0%} | {n:.0f} | {g:.0f} | {monthly:.0f} | {threshold(F, g)} | {threshold(H*F+K, H*g-a)} | {recovery} |")
    lines += [
        "",
        "Вывод о чувствительности: сочетание низкой комиссии, высокой поддержки и дорогого привлечения ломает вклад. "
        "Положительный результат требует подтверждения всех входов, включая доступную базу. "
        "Условные суммы подготовки бизнеса отличаются от предела стоимости исследовательского теста [E51]. "
        "Невозмещённые затраты теста входят в реальную смету запуска; нельзя повторно считать их и в A, и в K. "
        "Неизвестное распределение затрат трактуется консервативно, а не исключается.",
        "",
    ]
    stress_h = (D("8") - D("6")) / D("8")
    stress_g = D("600") - D("100") - stress_h * D("1000")
    stress_monthly = D("500") * stress_g - F
    stress_recovery = (K + D("500") * D("1000")) / stress_monthly
    lines += [
        "## Стресс первого продления",
        "",
        "Ориентир 6 из 8 [E35] соответствует 25% непродления первого цикла. "
        "Это не оценка стабильного месячного ухода; для ограничения риска используем отдельно как стресс [E42, E43].",
        "",
        f"При h_stress={stress_h:.0%} и остальных базовых входах g={stress_g:.0f} ₽/мес., "
        f"результат для 500 клиентов={stress_monthly:.0f} ₽/мес., срок покрытия начальных расходов={stress_recovery:.0f} месяцев. "
        f"Операционный порог={threshold(F, stress_g)}, "
        f"порог покрытия подготовки и первого привлечения за 12 месяцев={threshold(H*F+K, H*stress_g-D('1000'))}. "
        "Таким образом, ориентир продления сам по себе финансовый допуск не даёт.",
        "",
        "В реальном плане стресс = максимум из 10% и наблюдаемого непродления первой когорты [E43]. "
        "Выполнение условия покрытия за 12 месяцев при обоснованной доступной базе — ограничение следующего теста, "
        "не доказательство будущей прибыли.",
        "",
    ]
    (Path(__file__).resolve().parent / "strategy-economics.md").write_text("\n".join(lines), encoding="utf-8")
    print("Saved: work/strategy-economics.md")


if __name__ == "__main__":
    main()

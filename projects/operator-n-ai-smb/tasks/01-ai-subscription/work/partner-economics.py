"""Условная комиссия N; не предложения поставщиков и не прогноз."""
from decimal import Decimal, ROUND_CEILING
from pathlib import Path

D = Decimal
ROOT = Path(__file__).resolve().parent
FIXED, SETUP, MONTHS, CHURN = D("100000"), D("300000"), D("12"), D("0.05")
RECURRING = [
    ("Малая комиссия", D("300"), D("100"), D("1000")),
    ("Средняя комиссия", D("600"), D("100"), D("1000")),
    ("Большая комиссия", D("900"), D("100"), D("1000")),
    ("Дорогое обслуживание и продажа", D("600"), D("300"), D("3000")),
]


def ceiling_ratio(numerator, denominator):
    if denominator <= 0:
        return "нет"
    return format((numerator / denominator).to_integral_value(rounding=ROUND_CEILING), ".0f")


def main():
    lines = [
        "# Условная экономика партнёрского канала N",
        "",
        "Дата: 2026-11-11. Все входы — гипотезы [E27, E28, E29, E19]. "
        "Коммерческих условий и сметы N нет. Это проверка чувствительности.",
        "",
        "## Повторная комиссия",
        "",
        "C — чистая комиссия N с платящего клиента в месяц после расчётов с поставщиком, "
        "возвратов, скидок и косвенных налогов; тариф сервиса и API повторно не вычитаются. "
        "S — все собственные переменные расходы N на активного клиента в месяц; "
        "A — полная стоимость продажи и первичного подключения одного платящего клиента, включая неуспешные продажи. "
        "F — постоянные расходы канала в месяц, K — подготовка канала без первоначального привлечения клиентов. "
        "h — доля ухода в месяц. Лимиты расходов проверки из options.md к этим сценарным входам отношения не имеют.",
        "",
        "Допущения: F = 100 000 ₽/мес., K = 300 000 ₽, h = 5%, H = 12 месяцев. "
        "База N активных платящих достигается сразу в начале и затем постоянна; уход замещается новыми клиентами. "
        "Это условие сравнения, не реалистичный план роста. Для роста нужен помесячный план и дополнительное финансирование. "
        "Суммы после косвенных налогов, до налога на прибыль и финансирования.",
        "",
        "- g = C − S − h × A; месячный результат = N × g − F.",
        "- Операционный порог N = ceil(F / g), если g > 0.",
        "- Начальные расходы = K + N × A; первоначальное привлечение не потеряно и не смешано с замещением ухода.",
        "- Результат за H месяцев = H × (N × g − F) − K − N × A.",
        "- Для покрытия подготовки и первого привлечения за H: N = ceil((H × F + K) / (H × g − A)); "
        "если знаменатель ≤ 0, такого порога нет.",
        "",
        "Все суммы — ₽; N — активные платящие клиенты.",
        "",
        "| Сценарий | C/мес. | S/мес. | A | g/мес. | Операционный порог N | N для покрытия всех начальных расходов за 12 мес. |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, commission, servicing, acquisition in RECURRING:
        contribution = commission - servicing - CHURN * acquisition
        lines.append(
            f"| {name} | {commission:.0f} | {servicing:.0f} | {acquisition:.0f} | {contribution:.0f} | "
            f"{ceiling_ratio(FIXED, contribution)} | "
            f"{ceiling_ratio(MONTHS * FIXED + SETUP, MONTHS * contribution - acquisition)} |"
        )
    target_customers = D("500")
    max_acquisition = (
        MONTHS * (D("600") - D("100")) - (MONTHS * FIXED + SETUP) / target_customers
    ) / (1 + MONTHS * CHURN)
    lines += [
        "",
        "## Предел стоимости продажи",
        "",
        "Amax = (H × (C − S) − (H × F + K) / N) / (1 + H × h).",
        "",
        f"При C = 600, S = 100, N = 500 и остальных входах выше Amax = {max_acquisition:.0f} ₽. "
        "Это условный предел полной стоимости продажи и подключения для покрытия начальных затрат за 12 месяцев, "
        "не предложение партнёра. Сам размер базы 500 — допущение; он не подтверждён для N.",
        "",
        "## Разовая комиссия",
        "",
        "B = 2000 ₽ чистой разовой комиссии за нового платящего клиента. "
        "Повторной комиссии нет. Стабильная база N даёт h × N новых клиентов в месяц для замещения ухода. "
        "Месячный вклад на активного клиента g1 = h × (B − A) − S. "
        "Начальный результат первых продаж = N × (B − A) − K; "
        "он не превращается в повторную комиссию и не гарантирует дальнейший доход.",
        "",
        "| A | S/мес. | g1/мес. | Порог стабильной базы при F = 100 000 ₽/мес. |",
        "|---:|---:|---:|---:|",
    ]
    for acquisition, servicing in [(D("1000"), D("0")), (D("1000"), D("100")), (D("3000"), D("0"))]:
        contribution = CHURN * (D("2000") - acquisition) - servicing
        lines.append(
            f"| {acquisition:.0f} | {servicing:.0f} | {contribution:.0f} | {ceiling_ratio(FIXED, contribution)} |"
        )
    lines += [
        "",
        "Для потока разовых продаж без модели стабильной базы: "
        "нужное число новых платящих в месяц m >= (F + N × S) / (B − A), если B > A. "
        "При B <= A дополнительные продажи не покрывают расходы в этой модели. "
        "Выплаты, возвраты и отсрочки способны изменить денежный разрыв; здесь предполагается оплата без задержек. "
        "Для убыточного обслуживания стабильной базы нельзя обещать прибыль за счёт неизвестного потока новых клиентов.",
        "",
        "Положительный g подтверждает только условие операционного покрытия при достаточном N. "
        "Сравнивать пороги с собственной подпиской нельзя без одинаковых нагрузки, затрат и масштаба: "
        "фиксированные расходы здесь другие и тоже условные. Реальный срок возврата затрат и доступная база N неизвестны.",
        "",
    ]
    (ROOT / "partner-economics.md").write_text("\n".join(lines), encoding="utf-8")
    print("Saved: work/partner-economics.md")


if __name__ == "__main__":
    main()

"""Условная экономика; не данные N и не прогноз. Только стандартная библиотека."""
from decimal import Decimal, ROUND_CEILING
from pathlib import Path

D = Decimal
ROOT = Path(__file__).resolve().parent

# Опубликованные рублёвые тарифы с НДС, один источник: E9, E10.
RATES = {"Lite": D("0.2"), "Pro 5.1": D("0.8")}
# Условные входы E13–E19. Выручка после косвенных налогов и скидок.
REVENUES = [D("1000"), D("3000"), D("5000")]
REQUESTS = D("1000")
INPUT_TOKENS, OUTPUT_TOKENS = D("2000"), D("500")
CAC, CHURN = D("6000"), D("0.05")
FIXED = D("1000000")
FIXED_RANGE = [D("500000"), D("2000000")]
PROFILES = {
    "Базовый": (D("1"), D("500"), D("100")),
    "Сложный": (D("3"), D("1500"), D("200")),
}


def threshold(fixed, contribution):
    if contribution <= 0:
        return "нет"
    return format((fixed / contribution).to_integral_value(rounding=ROUND_CEILING), ".0f")


def main():
    lines = [
        "# Сценарная экономика подписки",
        "",
        "Дата: 2026-11-11. Условный расчёт для исследования, не прогноз прибыли N.",
        "",
        "## Входы и формулы",
        "",
        "Тарифы моделей — [E9, E10], один поставщик; синхронный режим, рубли с НДС. "
        "Остальные входы — гипотезы [E13, E14, E15, E16, E17, E18, E19]. Качество Lite и Pro не признано одинаковым.",
        "",
        "- M = генерации × (входящие токены × тариф входа + исходящие токены × тариф выхода) / 1000.",
        "- V = M + обслуживание + сторонние сервисы.",
        "- g = выручка на клиента − V − уход × стоимость привлечения и подключения.",
        "- Операционный результат стабильной базы = платящие клиенты × g − постоянные расходы.",
        "- Порог = округление вверх (постоянные расходы / g); при g ≤ 0 порога нет.",
        "",
        "Базовая нагрузка: 1000 генераций, каждая 2000 входящих и 500 исходящих токенов [E14]. "
        "Обслуживание: 500 ₽, сторонние сервисы: 100 ₽ [E15, E16]. "
        "Сложный сценарий: втрое больше генераций, обслуживание 1500 ₽, сервисы 200 ₽. "
        "Замещение ухода при постоянной базе: 6000 ₽ × 5% = 300 ₽ на активного клиента в месяц [E17, E19]. "
        "Постоянные расходы: 1 млн ₽ в месяц, чувствительность 0,5–2 млн ₽ [E18].",
        "",
        "## Результаты",
        "",
        "Все денежные столбцы — ₽ на платящего клиента в месяц; порог — активные платящие клиенты.",
        "",
        "| Сценарий | Модель | Выручка | Модель M | Все переменные V | Вклад g с замещением ухода | Порог при F = 1 млн |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for profile, (multiplier, support, services) in PROFILES.items():
        for model, rate in RATES.items():
            model_cost = REQUESTS * multiplier * (INPUT_TOKENS + OUTPUT_TOKENS) * rate / 1000
            variable = model_cost + support + services
            for revenue in REVENUES:
                contribution = revenue - variable - CHURN * CAC
                lines.append(
                    f"| {profile} | {model} | {revenue:.0f} | {model_cost:.0f} | "
                    f"{variable:.0f} | {contribution:.0f} | {threshold(FIXED, contribution)} |"
                )
    lines += [
        "",
        "## Чувствительность постоянных расходов",
        "",
        "При выручке 3000 ₽ и базовой нагрузке:",
        "",
        "| Модель | Порог при F = 0,5 млн ₽ | Порог при F = 2 млн ₽ |",
        "|---|---:|---:|",
    ]
    for model, rate in RATES.items():
        model_cost = REQUESTS * (INPUT_TOKENS + OUTPUT_TOKENS) * rate / 1000
        contribution = D("3000") - model_cost - D("500") - D("100") - CHURN * CAC
        lines.append(f"| {model} | {threshold(FIXED_RANGE[0], contribution)} | {threshold(FIXED_RANGE[1], contribution)} |")
    lines += [
        "",
        "## Границы расчёта",
        "",
        "Выручка — поступления N после косвенных налогов и скидок; стоимость API взята с НДС "
        "без предположения о его возмещении. Это консервативный денежный сценарий, не налоговая модель. "
        "Налог на прибыль и финансирование не учтены. Модель не доказывает окупаемость первоначальной разработки: "
        "её бюджет и срок неизвестны. Рост базы потребует отдельного финансирования новых подключений; "
        "здесь CAC учитывает только замещение ухода в стабильной базе.",
        "",
        "Генерация не равна диалогу Jivo: прямое сравнение себестоимости на диалог с [E4] недопустимо. "
        "Голос не моделируется. Хранение, поиск, инструменты и дополнительные сервисы должны попасть в "
        "измеренные затраты без двойного счёта; 100/200 ₽ — допущение, не смета.",
        "",
        "Для партнёрского пути: g = удерживаемая N выручка − выплаты партнёру − собственные переменные "
        "расходы − уход × CAC. Если входом служит уже чистая комиссия N, выплаты партнёру повторно не вычитать. "
        "Комиссия, обязанности и расходы N неизвестны; числового сравнения с собственным продуктом пока нет.",
        "",
        "Если конверсия доступной аудитории в платящих равна a, необходимая подходящая аудитория = порог / a. "
        "a и доступная аудитория N неизвестны; подстановка рыночной доли использования ИИ сюда не допускается.",
        "",
    ]
    target = ROOT / "economics.md"
    target.write_text("\n".join(lines), encoding="utf-8")
    print("Saved: work/economics.md")


if __name__ == "__main__":
    main()

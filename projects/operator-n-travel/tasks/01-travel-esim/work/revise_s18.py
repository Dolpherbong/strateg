def insert(name, heading, text):
    p = out / name
    old = read(p)
    marker = '## ' + heading + '\n'
    if marker not in old:
        raise SystemExit('Нет раздела: ' + name + ' / ' + heading)
    write(p, old.replace(marker, marker + '\n' + text.strip() + '\n', 1))


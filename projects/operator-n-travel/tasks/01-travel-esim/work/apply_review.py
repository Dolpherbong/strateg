def retire(text, record_id, status, reason, replacement):
    pattern = rf'(^### {record_id}\b[^\n]*\n)([\s\S]*?)(?=^### |\Z)'
    def change(match):
        body = re.sub(r'^- статус: действует$', '- статус: '+status, match[2], flags=re.M)
        if status == 'отозвано':
            body = body.rstrip() + '\n- причина: ' + reason + '\n'
        body = body.rstrip() + '\n- заменено: ' + replacement + '\n\n'
        return match[1] + body
    result, count = re.subn(pattern, change, text, count=1, flags=re.M)
    if count != 1:
        raise ValueError(record_id)
    return result

